#!/usr/bin/env node
// Regenerates web/THIRD_PARTY_NOTICES.md (NAV-002 AC 36) from the installed runtime dependencies, the vendored
// glyph/sprite licences and the licence texts kept in web/licenses/. Run after a dependency or asset upgrade:
//   node scripts/gen-third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(join(WEB, p), "utf8").trim();
const assetsCommit = read("public/fonts/BASEMAPS_ASSETS_COMMIT");

const dirs = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], { cwd: WEB, encoding: "utf8" })
  .trim()
  .split("\n")
  .slice(1);
const deps = [...new Map(dirs.map((d) => [d, JSON.parse(readFileSync(join(d, "package.json"), "utf8"))])).entries()]
  .map(([dir, p]) => {
    const repo = typeof p.repository === "string" ? p.repository : p.repository?.url ?? "";
    const url = repo
      .replace(/^git\+/, "")
      .replace(/^git:\/\//, "https://")
      .replace(/^git@github\.com:/, "https://github.com/")
      .replace(/^ssh:\/\/git@/, "https://")
      .replace(/^github:/, "https://github.com/")
      .replace(/^([\w-]+\/[\w.-]+)$/, "https://github.com/$1")
      .replace(/\.git$/, "");
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    const knownSource = { pmtiles: "https://github.com/protomaps/PMTiles" };
    return { name: p.name, version: p.version, license: p.license, url: url || knownSource[p.name] || `https://www.npmjs.com/package/${p.name}`, dir, file };
  })
  .filter((d, i, a) => a.findIndex((x) => x.name === d.name && x.version === d.version) === i)
  .sort((a, b) => a.name.localeCompare(b.name));

/**
 * Override sources for runtime packages whose npm tarball contains no licence file: the upstream licence text is kept
 * verbatim in web/licenses/ and reproduced here (BSD-3-Clause requires the copyright line, the conditions and the
 * disclaimer with a binary redistribution; the demo-mode build ships the Ferrostar WASM, ADR-0011 §10 Amendment 1).
 * `version` pins the copy to the upstream tag; the script fails when the installed version differs, so an upgrade
 * refreshes the copy instead of silently keeping an old text.
 */
const external = {
  pmtiles: { file: "licenses/pmtiles-LICENSE.txt", source: "https://github.com/protomaps/PMTiles/blob/main/LICENSE" },
  "@protomaps/basemaps": { file: "licenses/protomaps-basemaps-LICENSE.md", source: "https://github.com/protomaps/basemaps/blob/42ffaaa4/LICENSE.md" },
  "@stadiamaps/ferrostar": { file: "licenses/stadiamaps-ferrostar-LICENSE.txt", source: "https://github.com/stadiamaps/ferrostar/blob/0.57.0/LICENSE.txt", version: "0.57.0" },
};
for (const [name, o] of Object.entries(external)) {
  const d = deps.find((x) => x.name === name);
  if (d && o.version && d.version !== o.version) {
    throw new Error(`${name} ${d.version} is installed but ${o.file} is the ${o.version} licence text: refresh the copy from the upstream tag and update the version here`);
  }
}

let out = `# Third-party notices (web/)

Generated by \`scripts/gen-third-party-notices.mjs\` (NAV-002 AC 36, ADR-0004 §4). Do not edit by hand.

The web demo ships (a) static assets vendored under \`public/\` and (b) the runtime JavaScript libraries bundled by Vite.
Build and test tools (Vite, TypeScript, Vitest, ESLint) are not shipped and are not listed.

## 1. Bundled static assets

| Asset | Path in web/ | Source | Version / commit | Licence |
|---|---|---|---|---|
| Noto Sans Regular, Noto Sans Medium, Noto Sans Italic glyph PBFs (all 256 ranges each, generated by maplibre/font-maker) | \`public/fonts/<fontstack>/<range>.pbf\` | https://github.com/protomaps/basemaps-assets/tree/${assetsCommit}/fonts | basemaps-assets commit \`${assetsCommit}\` | SIL Open Font License 1.1 (full text in §3.1 and \`public/fonts/OFL.txt\`) |
| Map icon sprites \`light\`, \`dark\` (1x and 2x, JSON + PNG) | \`public/sprites/v4/\` | https://github.com/protomaps/basemaps-assets/tree/${assetsCommit}/sprites/v4 | basemaps-assets commit \`${assetsCommit}\` | Derived from MIT-licensed tangrams/icons (Mapzen); full text in §3.2. Protomaps basemap visual design: CC0 (§3.3) |
| Map style (layer definitions generated at runtime from the \`@protomaps/basemaps\` package, recoloured from docs/design/tokens.json) | bundled JS | https://github.com/protomaps/basemaps | npm \`@protomaps/basemaps\` ${deps.find((d) => d.name === "@protomaps/basemaps")?.version} | Code BSD-3-Clause, visual design CC0, some icons MIT (full text in §3.3) |

Checksums of every vendored file: \`public/SHA256SUMS\` (re-fetch with \`scripts/vendor-assets.sh\`).

Map data is not bundled: tiles are read at runtime from the gateway. They are © OpenStreetMap contributors (ODbL), and the
low-zoom landcover is © ESA WorldCover (CC BY 4.0). Both credits are shown on the map screen (NAV-002 AC 34–35).

## 2. Runtime JavaScript libraries (bundled into dist/)

| Package | Version | Licence | Source |
|---|---|---|---|
`;
for (const d of deps) out += `| \`${d.name}\` | ${d.version} | ${d.license} | ${d.url} |\n`;

out += `
## 3. Licence texts

### 3.1 SIL Open Font License 1.1 (Noto Sans glyphs)

\`\`\`text
${read("public/fonts/OFL.txt")}
\`\`\`

### 3.2 MIT License (tangrams/icons, source of the sprite icons)

Source: https://github.com/tangrams/icons/blob/master/LICENSE.md

\`\`\`text
${read("licenses/tangrams-icons-LICENSE.md")}
\`\`\`

### 3.3 @protomaps/basemaps (style code BSD-3-Clause, visual design CC0, icons MIT)

Source: https://github.com/protomaps/basemaps/blob/42ffaaa4/LICENSE.md

\`\`\`text
${read(external["@protomaps/basemaps"].file)}
\`\`\`

### 3.4 Runtime library licences

`;
for (const d of deps) {
  if (d.name === "@protomaps/basemaps") continue;
  let text;
  let from;
  if (d.file) {
    text = readFileSync(join(d.dir, d.file), "utf8").trim();
    from = `node_modules/${d.name}/${d.file}`;
  } else if (external[d.name] && existsSync(join(WEB, external[d.name].file))) {
    text = read(external[d.name].file);
    from = `${external[d.name].source} (upstream licence text, copied verbatim to web/${external[d.name].file}; the npm tarball contains no licence file)`;
  } else {
    text = `${d.license}. The npm package ships no licence file; see ${d.url}.`;
    from = "package.json";
  }
  out += `#### ${d.name} ${d.version} (${d.license})\n\nFrom ${from}.\n\n\`\`\`text\n${text}\n\`\`\`\n\n`;
}

writeFileSync(join(WEB, "THIRD_PARTY_NOTICES.md"), out.trimEnd() + "\n");
console.log(`THIRD_PARTY_NOTICES.md written: ${deps.length} runtime packages, glyphs + sprites @ ${assetsCommit}`);
