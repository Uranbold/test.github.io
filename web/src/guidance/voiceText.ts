// Voice text generator (navigation-ux §4.1; NAV-005 AC 32–33, NAV-017 AC 24–25; glossary C3, C3a, C4, A8–A13). 1:1
// port of the Android instructions/VoiceText.kt. Pure: the words come from the resource files through `t`, so the
// Mongolian and English texts share one code path. Units are spelled out («метрт», «километрт»), numbers stay digits,
// Mongolian decimal comma, English point. English distance templates have singular and plural forms: the singular only
// when the formatted number is exactly "1" (NAV-005-D4); the Mongolian items are identical. Valhalla text is never an
// input (ADR-0008).
//
// NAV-016 (the D95 coordinated change, AC 22–25, 47): a Mongolian prompt has three outputs, the display text (digits,
// the golden-set text), the spoken text (glossary C3a, from the canonical voice inventory generated from
// glossary-c3-spoken.tsv and the architect's inventory.tsv) and the ordered segment list (key + take, pack-format §6/§7).
// Mongolian km rounding: D92 for prefixes, D94 for continue-on, and no continue-on prompt at 995 km or more (D102).
// English is unchanged (D96): spoken = display, no segments. The web speaks the spoken text; it plays no clips (AC 49).
import type { Lang, MessageKey } from "../i18n/i18n";
import { capitalizeFirst, messageKey, type KeyResult } from "../route/instructions";
import inventoryJson from "./voiceInventory.json";

export type T = (key: MessageKey) => string;

/** What a voice prompt says. Language-neutral; rendered by `renderVoice`. */
export type VoiceContent =
  /** A manoeuvre prompt with the distance prefix from `distanceM` (none below 30 m), optionally chained (A13). */
  | { kind: "maneuver"; key: KeyResult; distanceM: number; then: KeyResult | null }
  /** The depart text at the start (§4.3), optionally chained with the first manoeuvre. */
  | { kind: "depart"; key: KeyResult; then: KeyResult | null }
  /** «{n} метрт очих газартаа хүрнэ» (A11). */
  | { kind: "approaching"; distanceM: number }
  /** «Та очих газартаа ирлээ» or the side variant. */
  | { kind: "arrival"; key: KeyResult }
  /** «{n} километр үргэлжлүүлэн явна уу» (A12). */
  | { kind: "continueOn"; distanceM: number };

export interface PrefixDistance {
  number: string;
  kilometres: boolean;
}

/** Take of a segment (pack-format §2.1): `nonFinal` only for a `{first}` instruction before «дараа нь». */
export type Take = "final" | "nonFinal";

/** One segment of a Mongolian prompt (ADR-0010 decision 2). */
export interface Segment {
  key: string;
  take: Take;
}

/** The three outputs of one prompt (NAV-016 AC 22). English: `spoken` = `display`, `segments` = []. */
export interface VoicePrompt {
  display: string;
  spoken: string;
  segments: Segment[];
}

/** The canonical voice inventory (pack-format §2.3): spoken text per `key` + take. */
export interface VoiceInventory {
  inventorySha256: string;
  spoken(key: string, take: Take): string | undefined;
}

export function voiceInventory(data: { inventorySha256: string; entries: readonly (readonly string[])[] }): VoiceInventory {
  const map = new Map<string, string>();
  for (const [key, take, text] of data.entries) map.set(`${key}\t${take}`, text!);
  return { inventorySha256: data.inventorySha256, spoken: (key, take) => map.get(`${key}\t${take}`) };
}

/** The inventory generated by scripts/gen-voice-inventory.mjs (voiceInventory.test.ts guards it against drift). */
export const VOICE_INVENTORY: VoiceInventory = voiceInventory(inventoryJson);

/** One decimal below 9,950 m («1,5», «,0» dropped), whole kilometres from 9,950 m. */
export function kilometres(d: number, lang: Lang): string {
  if (d >= 9950) return String(Math.round(d / 1000));
  const tenths = Math.round(d / 100);
  const whole = Math.trunc(tenths / 10);
  const frac = tenths % 10;
  return frac === 0 ? String(whole) : `${whole}${lang === "mn" ? "," : "."}${frac}`;
}

/** D92 (Mongolian voice prefix, d ≥ 995 m): «1» below 1,250 m, «1,5» below 1,750 m, then whole km half up. */
export function mongolianPrefixKilometres(d: number): string {
  if (d < 1250) return "1";
  if (d < 1750) return "1,5";
  return String(Math.round(d / 1000));
}

/**
 * D94 (Mongolian continue-on): whole km below 99,500 m, then the nearest 10 km; null at 995 km or more (D102: no
 * continue-on prompt is spoken).
 */
export function mongolianContinueKilometres(d: number): string | null {
  if (!Number.isFinite(d) || d >= 995_000) return null;
  if (d < 99_500) return String(Math.round(d / 1000));
  return String(Math.round(d / 10_000) * 10);
}

/** Distance prefix number and unit for `d` metres; null below 30 m (no prefix). */
export function prefixDistance(d: number, lang: Lang): PrefixDistance | null {
  if (!Number.isFinite(d) || d < 30) return null;
  if (d < 95) return { number: String(Math.round(d / 10) * 10), kilometres: false };
  if (d < 995) {
    const m = Math.round(d / 50) * 50;
    // D67: a metre value that rounds to 1000 is spoken «1 километрт» / "In 1 kilometer", never «1000 метрт».
    return m >= 1000 ? { number: "1", kilometres: true } : { number: String(m), kilometres: false };
  }
  return { number: lang === "mn" ? mongolianPrefixKilometres(d) : kilometres(d, lang), kilometres: true };
}

/** Metres for the approaching prompt (A11): the prefix rule in metres (≤ 500 m by the schedule, §4.3). */
function metres(d: number): string {
  return d < 95 ? String(Math.round(d / 10) * 10) : String(Math.round(d / 50) * 50);
}

/** CLDR `one` applied to the formatted number string (NAV-005-D4): only exactly "1". */
const isOne = (formatted: string): boolean => formatted === "1";

type PluralBase = "voice.prefixM" | "voice.prefixKm" | "voice.approaching" | "voice.continueOn";
function plural(t: T, base: PluralBase, n: string): string {
  return t(`${base}.${isOne(n) ? "one" : "other"}` as MessageKey).replace("{n}", n);
}

export function lowercaseFirst(s: string, lang: Lang): string {
  if (s === "") return s;
  const first = String.fromCodePoint(s.codePointAt(0)!);
  return first.toLocaleLowerCase(lang === "mn" ? "mn-MN" : "en-US") + s.slice(first.length);
}

const ORDINALS: readonly MessageKey[] = [
  "voice.ordinal.1",
  "voice.ordinal.2",
  "voice.ordinal.3",
  "voice.ordinal.4",
  "voice.ordinal.5",
  "voice.ordinal.6",
  "voice.ordinal.7",
  "voice.ordinal.8",
  "voice.ordinal.9",
  "voice.ordinal.10",
];

/** The instruction part of a manoeuvre (voice forms: A10 roundabout with the C4 ordinal). */
export function voiceInstruction(r: KeyResult, t: T): string {
  if (r.key === "roundabout.exit") {
    const n = r.params?.n;
    return n !== undefined && n >= 1 && n <= 10
      ? t("voice.roundaboutExit").replace("{ordinal}", () => t(ORDINALS[n - 1]!))
      : t("maneuver.roundabout.enter");
  }
  let text = t(messageKey(r.key));
  if (r.params) text = text.replace("{n}", String(r.params.n));
  return text;
}

function prefixed(d: number, instruction: string, lang: Lang, t: T): string {
  const dist = prefixDistance(d, lang);
  if (!dist) return capitalizeFirst(instruction, lang);
  const prefix = plural(t, dist.kilometres ? "voice.prefixKm" : "voice.prefixM", dist.number);
  const rest = lowercaseFirst(instruction, lang);
  return lang === "mn" ? `${prefix} ${rest}` : `${prefix}, ${rest}`;
}

function chained(first: string, then: KeyResult | null, lang: Lang, t: T): string {
  if (!then) return first;
  const second = lowercaseFirst(voiceInstruction(then, t), lang);
  // Function replacers: the inserted texts are used literally (no "$&"-style patterns).
  return capitalizeFirst(t("voice.then").replace("{first}", () => first).replace("{second}", () => second), lang);
}

/** The display text of one prompt in `lang` (VoiceText.render); null where no prompt is spoken (D102, `mn` only). */
export function renderVoice(c: VoiceContent, lang: Lang, t: T): string | null {
  switch (c.kind) {
    case "maneuver":
      return chained(prefixed(c.distanceM, voiceInstruction(c.key, t), lang, t), c.then, lang, t);
    case "depart":
      return chained(capitalizeFirst(voiceInstruction(c.key, t), lang), c.then, lang, t);
    case "approaching":
      return capitalizeFirst(plural(t, "voice.approaching", metres(c.distanceM)), lang);
    case "arrival":
      return capitalizeFirst(voiceInstruction(c.key, t), lang);
    case "continueOn": {
      const n = lang === "mn" ? mongolianContinueKilometres(c.distanceM) : kilometres(c.distanceM, lang);
      return n === null ? null : capitalizeFirst(plural(t, "voice.continueOn", n), lang);
    }
  }
}

/** ADR-0010 decision 2: the segment key of an instruction (`continue` → `instr.straight`, roundabout exit 1–10). */
export function instructionKey(r: KeyResult): string {
  if (r.key === "roundabout.exit") {
    const n = r.params?.n;
    return n !== undefined && n >= 1 && n <= 10 ? `instr.roundabout.exit.${n}` : "instr.roundabout.enter";
  }
  return r.key === "continue" ? "instr.straight" : `instr.${r.key}`;
}

/** The glossary-c3-spoken.tsv key of a distance prefix: `dist.m.300`, `dist.km.1`, `dist.km.1_5`, `dist.km.2`. */
export function distanceKey(dist: PrefixDistance): string {
  return dist.kilometres ? `dist.km.${dist.number.replace(",", "_")}` : `dist.m.${dist.number}`;
}

const seg = (key: string, take: Take = "final"): Segment => ({ key, take });

function instructionSegments(first: Segment[], then: KeyResult | null): Segment[] {
  if (!then) return first;
  const last = first[first.length - 1]!;
  return [...first.slice(0, -1), seg(last.key, "nonFinal"), seg("join.then"), seg(instructionKey(then))];
}

/** The Mongolian segment list of a prompt (ADR-0010 decision 2), or null where no prompt is spoken (D102). */
export function mongolianSegments(c: VoiceContent): Segment[] | null {
  switch (c.kind) {
    case "maneuver": {
      const dist = prefixDistance(c.distanceM, "mn");
      const instr = seg(instructionKey(c.key));
      return instructionSegments(dist ? [seg(distanceKey(dist)), instr] : [instr], c.then);
    }
    case "depart":
      return instructionSegments([seg(instructionKey(c.key))], c.then);
    case "approaching":
      return [seg(`dist.m.${metres(c.distanceM)}`), seg("tail.approach")];
    case "arrival":
      return [seg(instructionKey(c.key))];
    case "continueOn": {
      const n = mongolianContinueKilometres(c.distanceM);
      return n === null ? null : [seg(`cont.km.${n}`), seg("tail.continue")];
    }
  }
}

/**
 * pack-format §6 (AC 24): the spoken texts of the segments joined with one space, except «, » directly before
 * `join.then`. null if a segment has no inventory entry (a defect the domain tests rule out).
 */
export function spokenText(segments: readonly Segment[], inventory: VoiceInventory): string | null {
  let out = "";
  for (let i = 0; i < segments.length; i++) {
    const s = segments[i]!;
    const text = inventory.spoken(s.key, s.take);
    if (text === undefined) return null;
    out += i === 0 ? text : (s.key === "join.then" ? ", " : " ") + text;
  }
  return out;
}

/**
 * NAV-016 AC 22: display text, spoken text and segments of one prompt; null = no prompt (D102). Mongolian spoken text
 * comes only from the inventory (C3a: nothing is composed); a segment without an entry (impossible inside the AC 27
 * domain) falls back to the display text, lower-cased at the first letter.
 */
export function voicePrompt(c: VoiceContent, lang: Lang, t: T, inventory: VoiceInventory = VOICE_INVENTORY): VoicePrompt | null {
  const display = renderVoice(c, lang, t);
  if (display === null) return null;
  if (lang !== "mn") return { display, spoken: display, segments: [] };
  const segments = mongolianSegments(c) ?? [];
  return { display, spoken: spokenText(segments, inventory) ?? lowercaseFirst(display, lang), segments };
}
