#!/bin/sh
# SEC-4A BE-3: connection and bandwidth limits for the large static downloads (TILES /tiles/basemap.pmtiles and
# NAV-020 PACKS /packs/...). Writes ${NGINX_ENVSUBST_OUTPUT_DIR:-/etc/nginx/conf.d}/03-download-limits.conf (http
# level). Active only with GATEWAY_RATE_LIMIT=on (staging; dev default off, like the NAV-008 request limits):
#
#   GATEWAY_PACKS_MAX_CONN_PER_IP   pack file (.gz) downloads in flight per client (default 2, integer >= 1); over it -> 429
#   GATEWAY_PACKS_MAX_CONN          pack file (.gz) downloads in flight in total   (default 64, integer >= 1); over it -> 429
#                                   (the small manifest.json is not counted, so it can always be re-read)
#   GATEWAY_PACKS_LIMIT_RATE_AFTER  bytes of each /packs/ response sent at full speed (default 10m; nginx size)
#   GATEWAY_PACKS_LIMIT_RATE        bytes/s per /packs/ response after that (default 2m; 0 = no bandwidth limit)
#   GATEWAY_TILES_LIMIT_RATE_AFTER  bytes of each tiles response sent at full speed (default 4m; nginx size)
#   GATEWAY_TILES_LIMIT_RATE        bytes/s per tiles response after that (default 1m; 0 = no bandwidth limit)
#   GATEWAY_TILES_MAX_CONN_PER_IP   tiles requests (GET and HEAD, any Range) in flight per client (default 32; 0 = off;
#                                   1-23 refused: a phone alone opens up to 20, a browser over HTTP/2 about 20 on a
#                                   cold load, openapi 0.7.1 / ADR-0019 Amendment 1); over it -> 429 RateLimited
#                                   (headers only on HEAD). A connection cap, not a request rate: tile reads at any
#                                   rate stay unlimited (NAV-008 AC 13). SEC-4A BE-3 residual.
#
# How: as in 16/17, limit_conn and limit_rate are set at http level and inherited by every location, but the keys are
# empty and the rates 0 for everything that is not a GET/HEAD to the tiles file or under /packs/ (OPTIONS preflights
# included), so nothing else is touched. The TILES and PACKS locations set limit_conn_status 429 and send 429 to
# @rate_limited (GatewayError RateLimited, Retry-After 1, Cache-Control: no-store, CORS once). limit_rate counts bytes
# per response, so a Range request (PMTiles reads, offline-pack resume) gets its own initial burst: tile reads (a few
# KB to a few hundred KB) are never slowed, and a resumed pack download continues at the limited speed.
# Client key: $nav_client_key (gateway/njs/client.js; IPv4 full address, IPv6 /64), computed only for tiles/packs
# requests. The TILES and PACKS locations read $nav_dl_loaded (a constant defined only here), so nginx refuses to
# start when this file is missing.
# Privacy: keys live only in shared memory; "limiting connections" lines are logged at info, below the gateway's
# error_log level (crit), so client IPs never reach the logs.
set -eu

out="${NGINX_ENVSUBST_OUTPUT_DIR:-/etc/nginx/conf.d}/03-download-limits.conf"
mode="$(printf '%s' "${GATEWAY_RATE_LIMIT:-off}" | tr '[:upper:]' '[:lower:]')"
packs_ip="${GATEWAY_PACKS_MAX_CONN_PER_IP:-2}"
packs_all="${GATEWAY_PACKS_MAX_CONN:-64}"
packs_after="${GATEWAY_PACKS_LIMIT_RATE_AFTER:-10m}"
packs_rate="${GATEWAY_PACKS_LIMIT_RATE:-2m}"
tiles_after="${GATEWAY_TILES_LIMIT_RATE_AFTER:-4m}"
tiles_rate="${GATEWAY_TILES_LIMIT_RATE:-1m}"
tiles_ip="${GATEWAY_TILES_MAX_CONN_PER_IP:-32}"

bad() { echo "18-download-limits.sh: invalid $1: '$2' ($3)" >&2; exit 1; }

case "$mode" in on|off) ;; *) bad GATEWAY_RATE_LIMIT "$mode" "on or off" ;; esac
printf '%s' "$packs_ip" | grep -Eq '^[1-9][0-9]{0,5}$' || bad GATEWAY_PACKS_MAX_CONN_PER_IP "$packs_ip" "integer >= 1"
printf '%s' "$packs_all" | grep -Eq '^[1-9][0-9]{0,5}$' || bad GATEWAY_PACKS_MAX_CONN "$packs_all" "integer >= 1"
printf '%s' "$tiles_ip" | grep -Eq '^(0|[1-9][0-9]{0,5})$' || bad GATEWAY_TILES_MAX_CONN_PER_IP "$tiles_ip" "integer >= 0, 0 = off"
# openapi 0.7.1 / ADR-0019 Amendment 1: never below 24 (one phone keeps up to 20 tiles requests in flight).
[ "$tiles_ip" = 0 ] || [ "$tiles_ip" -ge 24 ] || bad GATEWAY_TILES_MAX_CONN_PER_IP "$tiles_ip" "0 = off, or an integer >= 24 (one client alone opens up to 20)"
for kv in "GATEWAY_PACKS_LIMIT_RATE_AFTER=$packs_after" "GATEWAY_PACKS_LIMIT_RATE=$packs_rate" \
          "GATEWAY_TILES_LIMIT_RATE_AFTER=$tiles_after" "GATEWAY_TILES_LIMIT_RATE=$tiles_rate"; do
    printf '%s' "${kv#*=}" | grep -Eq '^[0-9]{1,9}[km]?$' || bad "${kv%%=*}" "${kv#*=}" "bytes, optional k or m suffix, e.g. 2m"
done

{
    echo "# generated by 18-download-limits.sh (SEC-4A BE-3) from GATEWAY_RATE_LIMIT / GATEWAY_PACKS_* / GATEWAY_TILES_*"
    cat <<'EOF'
map $uri $nav_dl_loaded {
    default 1;
}
map $request_method $nav_dl_client {
    GET     $nav_client_key;
    HEAD    $nav_client_key;
    default "";
}
map $request_method $nav_dl_any {
    GET     dl;
    HEAD    dl;
    default "";
}
map $uri $nav_dl_tiles_key {
    /tiles/basemap.pmtiles $nav_dl_client;
    default                "";
}
map $uri $nav_dl_packs_key {
    ~^/packs/.+\.gz$ $nav_dl_client;
    default           "";
}
map $uri $nav_dl_packs_global_key {
    ~^/packs/.+\.gz$ $nav_dl_any;
    default           "";
}
EOF
    if [ "$mode" = on ]; then
        cat <<EOF
map \$uri \$nav_dl_rate_after {
    /tiles/basemap.pmtiles $tiles_after;
    ~^/packs/              $packs_after;
    default                0;
}
map \$uri \$nav_dl_rate {
    /tiles/basemap.pmtiles $tiles_rate;
    ~^/packs/              $packs_rate;
    default                0;
}
limit_conn_zone \$nav_dl_tiles_key        zone=nav_dl_tiles:10m;
limit_conn_zone \$nav_dl_packs_key        zone=nav_dl_packs:10m;
limit_conn_zone \$nav_dl_packs_global_key zone=nav_dl_packs_global:1m;
limit_conn nav_dl_packs        $packs_ip;
limit_conn nav_dl_packs_global $packs_all;
limit_rate_after \$nav_dl_rate_after;
limit_rate       \$nav_dl_rate;
EOF
        if [ "$tiles_ip" != 0 ]; then
            echo "limit_conn nav_dl_tiles        $tiles_ip;"
        fi
    fi
} > "$out"

printf '{"service":"gateway","level":"info","msg":"download limits configured","download_limits":"%s","packs":"%s per client, %s total, %s/s after %s","tiles":"%s/s after %s, %s in flight per client"}\n' \
    "$mode" "$packs_ip" "$packs_all" "$packs_rate" "$packs_after" "$tiles_rate" "$tiles_after" \
    "$( [ "$tiles_ip" = 0 ] && echo unlimited || echo "$tiles_ip")"
