#!/bin/sh
# SEC-2 (NAV-001 AC 49, ADR-0019 §3, openapi 0.7.0 RoutingBusy): /v1/route concurrency cap. ALWAYS on (dev, slots,
# staging), independent of GATEWAY_RATE_LIMIT. Writes ${NGINX_ENVSUBST_OUTPUT_DIR:-/etc/nginx/conf.d}/02-route-limits.conf
# (http level) from:
#
#   GATEWAY_ROUTE_MAX_INFLIGHT          /v1/route requests in flight in total       (default 8, integer >= 1)
#   GATEWAY_ROUTE_MAX_INFLIGHT_PER_IP   /v1/route requests in flight per client IP  (default 4, integer >= 1)
#
# How: limit_conn is set at http level and inherited by every location, but both keys are empty for every request
# that is not a GET/POST/HEAD to /v1/route (OPTIONS preflights included). nginx does not count requests with an empty
# key, so health, tiles, search, reverse, packs and preflights are never capped. A request over either cap is
# rejected in the preaccess phase with the PRIVATE status 529, which only the ROUTE location maps (error_page 529)
# to @route_busy = 503 GatewayError RoutingBusy + Retry-After: 1 + Cache-Control: no-store. The private code keeps
# the cap apart from an upstream 503 (mapped to 502 UpstreamUnavailable). Nothing is queued.
# The per-IP key is $nav_client_key (gateway/njs/client.js, SEC-4A BE-2): the real client IP after real_ip
# (16-rate-limits.sh, GATEWAY_REAL_IP_FROM on staging), IPv4 by full address and IPv6 by its /64 prefix.
# Privacy: keys live only in shared memory; "limiting connections" lines are logged at info, below the gateway's
# error_log level (crit), so client IPs never reach the logs.
set -eu

out="${NGINX_ENVSUBST_OUTPUT_DIR:-/etc/nginx/conf.d}/02-route-limits.conf"
max_total="${GATEWAY_ROUTE_MAX_INFLIGHT:-8}"
max_ip="${GATEWAY_ROUTE_MAX_INFLIGHT_PER_IP:-4}"

bad() { echo "17-route-limits.sh: invalid $1: '$2' (expected an integer >= 1; the cap cannot be switched off)" >&2; exit 1; }
printf '%s' "$max_total" | grep -Eq '^[1-9][0-9]{0,5}$' || bad GATEWAY_ROUTE_MAX_INFLIGHT "$max_total"
printf '%s' "$max_ip" | grep -Eq '^[1-9][0-9]{0,5}$' || bad GATEWAY_ROUTE_MAX_INFLIGHT_PER_IP "$max_ip"

cat > "$out" <<EOF
# generated by 17-route-limits.sh (SEC-2) from GATEWAY_ROUTE_MAX_INFLIGHT / GATEWAY_ROUTE_MAX_INFLIGHT_PER_IP
map \$request_method \$nav_rc_client {
    OPTIONS "";
    default \$nav_client_key;
}
map \$request_method \$nav_rc_global {
    OPTIONS "";
    default route;
}
map \$uri \$nav_rc_ip_key {
    /v1/route \$nav_rc_client;
    default   "";
}
map \$uri \$nav_rc_global_key {
    /v1/route \$nav_rc_global;
    default   "";
}
limit_conn_zone \$nav_rc_global_key zone=nav_route_global:1m;
limit_conn_zone \$nav_rc_ip_key     zone=nav_route_ip:10m;
limit_conn nav_route_global $max_total;
limit_conn nav_route_ip     $max_ip;
limit_conn_status    529;
limit_conn_log_level info;
EOF

printf '{"service":"gateway","level":"info","msg":"route concurrency cap configured","route_max_inflight":"%s","route_max_inflight_per_ip":"%s"}\n' \
    "$max_total" "$max_ip"
