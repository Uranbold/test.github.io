    /**
     * TC-D10 (AC 19, ADR-0013 Amendment 2 steps 3–4, run 3): the TC-D07 restore while STANDING on the G10 return
     * carriageway, but with a poor (still "good", ≤ 25 m) accuracy of 25 m, as is usual for a stationary phone between
     * buildings. The tie margin max(10 m, 25 m) then covers the outbound carriageway (~22.5 m away), so the start step
     * may be the earlier one (the residual risk the ADR accepts). Required: the one bearing re-check, at the first
     * driving fix, moves the session to step 1 with 0 route requests; no U-turn prompt after that; at most one extra
     * manoeuvre prompt in total (ADR Amendment 2 step 4); exactly one arrival at the destination.
     */
    @Test
    fun tcD10_g10RestoreStandingWithPoorAccuracyIsCorrectedByTheBearingRecheck() {
        HostFerrostar.require()
        val g = g10()
        val r = g.r
        val line = r.initial.plan.geometry
        val at = Geo.along(line, g.restoreAt)
        val standing = (1..4).map { Tracks.fix(at, it * 1_000L, null, 0.0, accuracy = 25.0) }
        val driving = Tracks.along(line, 8.0, t0 = 5_000, fromM = g.restoreAt + 8.0)
        r.run(standing + driving, tailMs = 10_000, restoredAt = 0)
        val log = r.log.filter { it.startsWith("restore") }
        println("TC-D10 log: $log")
        println("TC-D10 spoken: " + r.spoken.map { "${it.first / 1000.0}s ${it.second.maneuver} ${it.second.text}" })
        val p = ArrayList<String>()
        val start = log.firstNotNullOfOrNull { Regex("restore start step (\\d+)").find(it)?.groupValues?.get(1)?.toInt() }
        if (start == null) p += "no restore start step logged"
        if (start == 0 && log.none { it.contains("re-check: step 0 -> 1") }) p += "start step 0 was not corrected to step 1 by the bearing re-check: $log"
        val firstDriving = driving.first().elapsedMs
        r.spoken.filter { it.first > firstDriving && it.second.maneuver?.second == 1 }
            .forEach { p += "U-turn prompt after the bearing re-check at ${it.first / 1000.0} s: «${it.second.text}»" }
        val maneuverPrompts = r.spoken.filter { it.second.cls == PromptClass.MANEUVER }
        // One restore prompt + at most one re-check catch-up; the arrival itself is the next manoeuvre.
        val nonArrival = maneuverPrompts.filter { it.second.maneuver?.second != 2 }
        if (nonArrival.size > 1) p += "more than one extra manoeuvre prompt: ${nonArrival.map { it.second.text }}"
        if (r.requests.isNotEmpty()) p += "AC 19/20: ${r.requests.size} route requests on the stored route"
        val arrivals = r.events.count { it.second == GuidanceEvent.Arrived }
        if (arrivals != 1) p += "AC 19: $arrivals arrivals (expected 1)"
        assertTrue(p.joinToString("\n"), p.isEmpty())
    }

    /**
     * TC-D09 (AC 24, 21): crash loop across simulated process deaths through [RestoreManager] (each "process" is a new
     * manager on the same directory; a restore records itself exactly as [mn.navmn.app.engine.GuidanceSession.restore]
     * does). Interruptions at 2, 4 and 6 min: restores 1 and 2 happen, the third interruption deletes the record and
     * opens the map screen (no restore). Control: a third interruption 10+ min after the first restore restores.
     */
    @Test
    fun tcD09_crashLoopLimitAcrossProcessDeaths() {
        val t0 = 1_790_000_000_000L
        val route = (RouteProcessor(FakeRouteParser()).process(Fixtures.route("p1-p3-car-mn.json"), 0) as RouteOutcome.Ok).route
        val trip = Trip(LatLon(47.8858, 106.9173), "Зайсан толгой", TravelMode.CAR, avoidUnpaved = false)
        // The first «Эхлэх» write must land before the first interruption: use a scope we can flush.
        fun startedDir(name: String): File {
            val dir = File(tmp.root, name)
            val scope = TestScope(StandardTestDispatcher())
            val m = RestoreManager(RestoreStore(dir), null, { t0 }, scope)
            m.onGuidanceStarted(trip, route, Lang.MN)
            scope.runCurrent()
            assertTrue("record written at «Эхлэх»", RestoreStore(dir).read() is StoredRecord.Present)
            return dir
        }
        fun restoreOnly(dir: File, interruptions: List<Long>): List<RestoreRules.Decision> {
            val decisions = ArrayList<RestoreRules.Decision>()
            for (at in interruptions) {
                val now = t0 + at
                val scope = TestScope(StandardTestDispatcher())
                val m = RestoreManager(RestoreStore(dir), null, { now }, scope)
                val d = m.decide(sessionAlive = false, locationOk = true)
                decisions += d
                if (d is RestoreRules.Decision.Restore) {
                    m.onGuidanceStarted(trip, route, Lang.MN, restored = RestoreRules.afterRestore(d.meta, now))
                    scope.runCurrent()
                } else if (d is RestoreRules.Decision.DeleteSilently) {
                    m.delete()
                }
            }
            return decisions
        }
        val loopDir = startedDir("loop")
        val loop = restoreOnly(loopDir, listOf(2 * 60_000L, 4 * 60_000L, 6 * 60_000L))
        assertTrue("1st interruption restores: ${loop[0]}", loop[0] is RestoreRules.Decision.Restore)
        assertTrue("2nd interruption restores: ${loop[1]}", loop[1] is RestoreRules.Decision.Restore)
        assertEquals("3rd interruption within 10 min", RestoreRules.Decision.DeleteSilently(RestoreRules.Reason.LOOP_LIMIT), loop[2])
        assertFalse("record deleted (map screen, no notice)", loopDir.exists())

        val slowDir = startedDir("slow")
        val slow = restoreOnly(slowDir, listOf(2 * 60_000L, 4 * 60_000L, 13 * 60_000L))
        assertTrue("restores at 2, 4 and 13 min (the 2 min restore is outside the 10 min window at 13 min): $slow", slow.all { it is RestoreRules.Decision.Restore })
        // AC 21: 31 min after the last heartbeat the record is deleted silently.
        val expired = restoreOnly(slowDir, listOf(13 * 60_000L + 30 * 60_000L + 1))
        assertEquals(RestoreRules.Decision.DeleteSilently(RestoreRules.Reason.EXPIRED), expired.single())
        assertFalse(slowDir.exists())
    }
