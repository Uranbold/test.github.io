    // ------------------------------------------------------------------------------------------------ sun (H)

    private val fixture: JsonObject by lazy { Json.parseToJsonElement(repoFile("tests/android/nav012/noaa-sun-fixture.json").readText()).jsonObject }

    private data class Row(val point: String, val lat: Double, val lon: Double, val date: LocalDate, val rise: Instant, val set: Instant)

    private val rows: List<Row> by lazy {
        fixture["rows"]!!.jsonArray.map { it.jsonObject }.map {
            Row(
                it["point"]!!.jsonPrimitive.content,
                it["lat"]!!.jsonPrimitive.double,
                it["lon"]!!.jsonPrimitive.double,
                LocalDate.parse(it["localDate"]!!.jsonPrimitive.content),
                Instant.parse(it["sunriseUtc"]!!.jsonPrimitive.content),
                Instant.parse(it["sunsetUtc"]!!.jsonPrimitive.content),
            )
        }
    }

    private fun <T> inZone(id: String, block: () -> T): T {
        val saved = TimeZone.getDefault()
        TimeZone.setDefault(TimeZone.getTimeZone(id))
        try {
            return block()
        } finally {
            TimeZone.setDefault(saved)
        }
    }

    /**
     * TC-H01 (AC 40): sunrise and sunset for P1, X1, K1, Z1 on the four AC 40 dates within ±2 min of the NOAA Solar
     * Calculator. The local date (Asia/Ulaanbaatar or Asia/Hovd) is the date of the solar day; the app computes in UTC
     * around that day's solar noon. Run in three device time zones (AC 41: the zone must not change the result).
     */
    @Test
    fun tcH01_noaaFixtureFourPointsFourDatesWithinTwoMinutes() {
        assertEquals("fixture rows", 16, rows.size)
        val tol = fixture["toleranceMinutes"]!!.jsonPrimitive.int.toDouble()
        val p = ArrayList<String>()
        var worst = 0.0
        for (zone in listOf("UTC", "Asia/Ulaanbaatar", "Asia/Hovd", "America/Los_Angeles")) inZone(zone) {
            for (r in rows) {
                val t = SunCalc.sunTimes(r.date, r.lat, r.lon)
                if (t !is SunTimes.Rise) {
                    p += "$zone ${r.point} ${r.date}: $t, NOAA has a sunrise and a sunset"
                    continue
                }
                val dr = SunCalc.minutesBetween(t.sunrise, r.rise)
                val ds = SunCalc.minutesBetween(t.sunset, r.set)
                worst = maxOf(worst, dr, ds)
                if (dr > tol) p += "$zone ${r.point} ${r.date}: sunrise ${t.sunrise} vs NOAA ${r.rise} (${"%.2f".format(dr)} min)"
                if (ds > tol) p += "$zone ${r.point} ${r.date}: sunset ${t.sunset} vs NOAA ${r.set} (${"%.2f".format(ds)} min)"
            }
        }
        println("TC-H01 worst deviation from NOAA: ${"%.3f".format(worst)} min over ${rows.size * 2} values x 4 zones")
        assertTrue(p.joinToString("\n"), p.isEmpty())
    }

    /**
     * TC-H02 (AC 41, 44): the theme decision itself ([SunCalc.isDay] → [ThemeResolver] «Автомат») flips at the NOAA
     * times: night 3 min before NOAA sunrise, day 3 min after; day 3 min before NOAA sunset, night 3 min after. Same
     * result in every device time zone. «Өдрийн горим» / «Шөнийн горим» ignore the sun (AC 43).
     */
    @Test
    fun tcH02_autoThemeFlipsAtTheNoaaTimesInEveryTimeZone() {
        val p = ArrayList<String>()
        val margin = 3 * 60_000L
        for (zone in listOf("UTC", "Asia/Hovd", "Pacific/Kiritimati", "America/Los_Angeles")) inZone(zone) {
            for (r in rows) {
                fun night(at: Instant) = ThemeResolver.night(ThemeChoice.AUTO, !SunCalc.isDay(at, r.lat, r.lon))
                val checks = listOf(
                    Triple("rise-3", r.rise.minusMillis(margin), true),
                    Triple("rise+3", r.rise.plusMillis(margin), false),
                    Triple("set-3", r.set.minusMillis(margin), false),
                    Triple("set+3", r.set.plusMillis(margin), true),
                )
                for ((name, at, expectNight) in checks) {
                    if (night(at) != expectNight) p += "$zone ${r.point} ${r.date} $name ($at): night=${night(at)}, expected $expectNight"
                }
                if (ThemeResolver.night(ThemeChoice.DAY, true)) p += "DAY follows the sun"
                if (!ThemeResolver.night(ThemeChoice.NIGHT, false)) p += "NIGHT follows the sun"
            }
        }
        assertTrue(p.joinToString("\n"), p.isEmpty())
    }

    // ------------------------------------------------------------------------------------------- restore (D)

    /** G10 restore setup: a point on the return carriageway after the U-turn, ≤ 50 m from the outbound carriageway. */
    private class G10Restore(val r: Replay, val restoreAt: Double, val uturnAlong: Double, val length: Double, val gapToOutbound: Double)

    private fun g10(): G10Restore {
        val r = Replay(QaGpx.routeBytes("G10"), TravelMode.CAR, Lang.MN)
        val plan = r.initial.plan
        val oracle = RouteOracle(plan)
        assertEquals("fixture: G10 has depart, U-turn, arrive", 3, plan.steps.size)
        val uturnAlong = oracle.maneuverAlong[1]
        val line = plan.geometry
        val length = Geo.length(line)
        val restoreAt = uturnAlong + (length - uturnAlong) * 0.6
        val outbound = ArrayList<LatLon>()
        var d = 0.0
        while (d < uturnAlong - 40.0) {
            outbound += Geo.along(line, d)
            d += 5.0
        }
        val gap = Geo.distanceToLine(Geo.along(line, restoreAt), outbound)
        assertTrue("fixture: restore point ${gap.toInt()} m from the outbound carriageway (needs <= 50 m)", gap <= 50.0)
        return G10Restore(r, restoreAt, uturnAlong, length, gap)
    }

    private fun restoreProblems(g: G10Restore, firstFixAt: Long): List<String> {
        val r = g.r
        val p = ArrayList<String>()
        val uturnText = mn[StringKey.MANEUVER_UTURN]
        val start = r.log.firstNotNullOfOrNull { Regex("restore start step (\\d+)").find(it)?.groupValues?.get(1)?.toInt() }
        if (start != 1) p += "AC 19: restore start step $start (the true position is on step 1, after the U-turn)"
        val early = r.spoken.filter { it.first in firstFixAt..firstFixAt + 3_000 && it.second.cls == PromptClass.MANEUVER }
        if (early.size != 1) p += "AC 19: ${early.size} manoeuvre prompts within 3 s of the first good fix: ${early.map { it.second.text }}"
        early.filter { it.second.maneuver?.second == 1 }.forEach { p += "AC 19: restore prompt is for the U-turn already made: «${it.second.text}»" }
        r.spoken.filter { it.second.maneuver?.second == 1 || it.second.text.lowercase().contains(uturnText.lowercase().substringBefore(" ")) }.forEach {
            p += "AC 19: U-turn prompt after the restore at ${it.first / 1000.0} s: «${it.second.text}»"
        }
        if (r.requests.isNotEmpty()) p += "AC 19/20: ${r.requests.size} route requests on the stored route"
        val arrivals = r.events.count { it.second == GuidanceEvent.Arrived }
        if (arrivals != 1) p += "AC 19: $arrivals arrivals (expected 1 at the end of the stored route)"
        return p
    }

    /**
     * TC-D07 (AC 19): restore while STANDING on the G10 return carriageway (first good fixes: speed 0, no bearing, as
     * when the driver reopens the app at a red light), then drive on to the destination. Expected: start step 1 (after
     * the U-turn), exactly one prompt for the next manoeuvre (the arrival), never the U-turn again, 0 requests, one
     * arrival.
     */
    @Test
    fun tcD07_g10RestoreStandingOnTheReturnCarriageway() {
        HostFerrostar.require()
        val g = g10()
        val line = g.r.initial.plan.geometry
        val at = Geo.along(line, g.restoreAt)
        val standing = (1..4).map { Tracks.fix(at, it * 1_000L, null, 0.0) }
        val driving = Tracks.along(line, 8.0, t0 = 5_000, fromM = g.restoreAt + 8.0)
        g.r.run(standing + driving, tailMs = 10_000, restoredAt = 0)
        println("TC-D07 restore point ${g.restoreAt.toInt()} m along (U-turn at ${g.uturnAlong.toInt()} m, route ${g.length.toInt()} m), ${"%.1f".format(g.gapToOutbound)} m from the outbound carriageway")
        println("TC-D07 log: " + g.r.log.filter { it.startsWith("restore") })
        println("TC-D07 spoken: " + g.r.spoken.map { "${it.first / 1000.0}s ${it.second.maneuver} ${it.second.text}" })
        val p = restoreProblems(g, standing.first().elapsedMs)
        assertTrue(p.joinToString("\n"), p.isEmpty())
    }

